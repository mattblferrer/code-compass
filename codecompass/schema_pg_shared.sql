-- Hosted mode (R-50): the tables every account shares, in the public schema.
-- Safe to rerun: this runs at each start. Each account's own tables are in schema_pg_user.sql.
-- Column names and meanings follow schema.sql and docs/data_model.md.

CREATE TABLE IF NOT EXISTS app_meta (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

INSERT INTO app_meta (key, value) VALUES ('schema_version', '1') ON CONFLICT DO NOTHING;

-- Accounts (R-51). Only the GitHub account's ID and names are kept; no password.
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    github_id BIGINT NOT NULL UNIQUE,
    login TEXT NOT NULL,
    name TEXT,
    created TEXT NOT NULL
);

-- Signed-in sessions. The browser holds the token; only its hash is kept, and signing out
-- deletes the row, so a copied cookie stops working (R-51).
CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created DOUBLE PRECISION NOT NULL,
    last_used DOUBLE PRECISION NOT NULL
);

CREATE INDEX IF NOT EXISTS sessions_by_user ON sessions (user_id);

-- When each site may next be sent a request, across every account (R-54).
CREATE TABLE IF NOT EXISTS site_clock (
    host TEXT PRIMARY KEY,
    next_at DOUBLE PRECISION NOT NULL
);

-- Requests counted per key and window, for the limits in R-53.
CREATE TABLE IF NOT EXISTS rate_limits (
    key TEXT PRIMARY KEY,
    window_start DOUBLE PRECISION NOT NULL,
    count INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS patterns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    category TEXT NOT NULL CHECK (category IN ('core', 'advanced')),
    tier TEXT NOT NULL CHECK (tier IN ('narrow', 'normal', 'broad')),
    family TEXT NOT NULL DEFAULT '',
    description TEXT NOT NULL,
    list_position INTEGER NOT NULL
);

-- The catalog and reserve, shared, plus each account's custom problems, marked with their
-- owner. Accounts reach this table through their own `problems` view (schema_pg_user.sql).
CREATE TABLE IF NOT EXISTS problems (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    link TEXT,
    difficulty TEXT NOT NULL CHECK (difficulty IN ('easy', 'medium', 'hard', 'very hard')),
    rating INTEGER,
    source TEXT NOT NULL,
    is_custom INTEGER NOT NULL DEFAULT 0 CHECK (is_custom IN (0, 1)),
    catalog_position INTEGER,
    reserve_position INTEGER,
    owner BIGINT REFERENCES users (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS problems_shared_link ON problems (link) WHERE owner IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS problems_owned_link ON problems (owner, link) WHERE owner IS NOT NULL;
CREATE INDEX IF NOT EXISTS problems_by_owner ON problems (owner);

CREATE TABLE IF NOT EXISTS problem_patterns (
    problem_id BIGINT NOT NULL REFERENCES problems (id) ON DELETE CASCADE,
    pattern_id BIGINT NOT NULL REFERENCES patterns (id),
    PRIMARY KEY (problem_id, pattern_id)
);

-- Shared problems and their patterns change only while the catalog loads, which sets
-- codecompass.catalog for its transaction. An account's requests can change only its own
-- custom problems, whatever a query asks (R-52).
CREATE OR REPLACE FUNCTION guard_shared_problem() RETURNS trigger AS $$
BEGIN
    IF coalesce(current_setting('codecompass.catalog', true), '') <> 'on' THEN
        IF (TG_OP <> 'INSERT' AND OLD.owner IS NULL) OR (TG_OP <> 'DELETE' AND NEW.owner IS NULL) THEN
            RAISE EXCEPTION 'Shared problems change only when the catalog loads.';
        END IF;
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER guard_shared_problem BEFORE INSERT OR UPDATE OR DELETE ON problems
    FOR EACH ROW EXECUTE FUNCTION guard_shared_problem();

CREATE OR REPLACE FUNCTION guard_shared_problem_patterns() RETURNS trigger AS $$
DECLARE
    problem_owner BIGINT;
    found_problem BOOLEAN;
BEGIN
    IF coalesce(current_setting('codecompass.catalog', true), '') <> 'on' THEN
        SELECT owner, true INTO problem_owner, found_problem FROM problems
            WHERE id = CASE WHEN TG_OP = 'DELETE' THEN OLD.problem_id ELSE NEW.problem_id END;
        -- A missing problem means its own deletion is cascading here, which the guard above allowed.
        IF found_problem AND problem_owner IS NULL THEN
            RAISE EXCEPTION 'Shared problems change only when the catalog loads.';
        END IF;
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER guard_shared_problem_patterns BEFORE INSERT OR UPDATE OR DELETE ON problem_patterns
    FOR EACH ROW EXECUTE FUNCTION guard_shared_problem_patterns();
