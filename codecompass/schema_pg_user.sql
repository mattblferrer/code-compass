-- Hosted mode (R-50, R-52): one account's tables, in that account's own schema, which
-- ensure_user_schema (pg.py) sets as the search path before running this. {owner} is the
-- account's id. Safe to rerun. The tables match schema.sql; docs/data_model.md describes them.

CREATE TABLE IF NOT EXISTS app_meta (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

INSERT INTO app_meta (key, value) VALUES ('schema_version', '1') ON CONFLICT DO NOTHING;

-- The shared catalog and reserve, and this account's custom problems. Inserts through the
-- view are owned by the account, and the check option keeps every change within it.
CREATE OR REPLACE VIEW problems AS
    SELECT * FROM public.problems WHERE owner IS NULL OR owner = {owner}
    WITH CHECK OPTION;

ALTER VIEW problems ALTER COLUMN owner SET DEFAULT {owner};

CREATE TABLE IF NOT EXISTS attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id BIGINT NOT NULL REFERENCES public.problems (id),
    date TEXT NOT NULL,
    outcome TEXT NOT NULL CHECK (outcome IN ('solved_alone', 'solved_with_hints', 'solved_after_solution', 'not_solved')),
    time_seconds INTEGER CHECK (time_seconds IS NULL OR time_seconds >= 1),
    notes TEXT,
    entry_method TEXT NOT NULL CHECK (entry_method IN ('manual', 'csv', 'sync')),
    review_of_problem_id BIGINT REFERENCES public.problems (id)
);

CREATE INDEX IF NOT EXISTS attempts_by_problem ON attempts (problem_id, date);

CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY CHECK (key IN ('starting_difficulty', 'advanced_on', 'very_hard_on', 'reviews_on', 'weekly_goal')),
    value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS interviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company TEXT NOT NULL,
    date TEXT NOT NULL,
    target_difficulty TEXT CHECK (target_difficulty IS NULL OR target_difficulty IN ('easy', 'medium', 'hard', 'very hard')),
    daily_target INTEGER
);

CREATE TABLE IF NOT EXISTS interview_patterns (
    interview_id BIGINT NOT NULL REFERENCES interviews (id) ON DELETE CASCADE,
    pattern_id BIGINT NOT NULL REFERENCES public.patterns (id),
    PRIMARY KEY (interview_id, pattern_id)
);

CREATE TABLE IF NOT EXISTS hidden_sites (
    site TEXT NOT NULL CHECK (site IN ('leetcode', 'codeforces', 'cses', 'atcoder')),
    category TEXT NOT NULL CHECK (category IN ('core', 'advanced')),
    PRIMARY KEY (site, category)
);

CREATE TABLE IF NOT EXISTS pattern_preferences (
    pattern_id BIGINT PRIMARY KEY REFERENCES public.patterns (id),
    preference TEXT NOT NULL CHECK (preference IN ('target', 'mastered'))
);

CREATE TABLE IF NOT EXISTS sibling_suggestions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    due_problem_id BIGINT NOT NULL REFERENCES public.problems (id) ON DELETE CASCADE,
    sibling_problem_id BIGINT NOT NULL REFERENCES public.problems (id) ON DELETE CASCADE,
    status TEXT NOT NULL CHECK (status IN ('active', 'dismissed')),
    date TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS not_now (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id BIGINT NOT NULL REFERENCES public.problems (id) ON DELETE CASCADE,
    date TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS hint_reveals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id BIGINT NOT NULL REFERENCES public.problems (id) ON DELETE CASCADE,
    date TEXT NOT NULL,
    used INTEGER NOT NULL DEFAULT 0 CHECK (used IN (0, 1))
);

CREATE TABLE IF NOT EXISTS linked_accounts (
    site TEXT NOT NULL CHECK (site IN ('codeforces', 'atcoder', 'leetcode')),
    username TEXT NOT NULL,
    last_synced TEXT,
    PRIMARY KEY (site, username)
);

CREATE TABLE IF NOT EXISTS sync_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site TEXT NOT NULL,
    username TEXT NOT NULL,
    problem_link TEXT NOT NULL,
    title TEXT NOT NULL,
    date TEXT NOT NULL,
    accepted INTEGER NOT NULL CHECK (accepted IN (0, 1)),
    rating INTEGER,
    tags TEXT,
    status TEXT NOT NULL CHECK (status IN ('pending', 'confirmed', 'dismissed')),
    UNIQUE (site, problem_link, date)
);

-- rowid keeps the order ratings were stored in, as SQLite's built-in rowid does.
CREATE TABLE IF NOT EXISTS rating_history (
    site TEXT NOT NULL,
    username TEXT NOT NULL,
    contest TEXT NOT NULL,
    date TEXT NOT NULL,
    rating INTEGER NOT NULL,
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY (site, username, contest)
);

CREATE TABLE IF NOT EXISTS deleted_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL CHECK (kind IN ('attempt', 'interview')),
    payload TEXT NOT NULL,
    date TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS sync_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payload TEXT NOT NULL,
    date TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS problem_notes (
    problem_id BIGINT PRIMARY KEY REFERENCES public.problems (id) ON DELETE CASCADE,
    note TEXT NOT NULL,
    updated TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS problem_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id BIGINT NOT NULL REFERENCES public.problems (id) ON DELETE CASCADE,
    url TEXT NOT NULL,
    label TEXT
);

-- Hosted only: the account's data as a backup file, kept so deleting all data or a
-- restore can be undone (R-39, R-46). Local mode keeps this copy as a file instead.
CREATE TABLE IF NOT EXISTS kept_copy (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    data BYTEA NOT NULL
);

-- Hosted only: the account's sync while it runs in steps (R-54), saved between requests.
-- `lease` is when the step running it ends, so two open pages never run it at once.
CREATE TABLE IF NOT EXISTS sync_job (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    data TEXT NOT NULL,
    lease DOUBLE PRECISION NOT NULL DEFAULT 0
);
