"""Compare the rules in codecompass/core with tests/data/reference.json.

The reference data is generated by tests/data/generate_reference.py. If a rule
changes on purpose, regenerate it and review the differences.
"""
import json
from pathlib import Path

import pytest

from codecompass.core import constants as c
from codecompass.core.levels import atcoder_level, codeforces_level, current_level
from codecompass.core.mastery import pattern_score
from codecompass.core.recommend import interview_focus, recommend
from codecompass.core.schedule import review_schedule
from codecompass.core.siblings import choose_sibling
from codecompass.core.streak import review_streak

REFERENCE = json.loads((Path(__file__).parent / "data" / "reference.json").read_text(encoding="utf-8"))

OUTCOME = {
    "alone": c.SOLVED_ALONE,
    "hints": c.SOLVED_WITH_HINTS,
    "solution": c.SOLVED_AFTER_SOLUTION,
    "not": c.NOT_SOLVED,
}


def cases(section):
    return pytest.mark.parametrize("case", REFERENCE[section], ids=lambda case: case["name"])


@cases("mastery")
def test_mastery(case):
    attempts = [{**a, "outcome": OUTCOME[a["outcome"]]} for a in case["attempts"]]
    score = pattern_score(attempts, case["tier"], case["today"])
    if case["expected_score"] is None:
        assert score is None
    else:
        assert score == pytest.approx(case["expected_score"], abs=0.01)


@cases("intervals")
def test_intervals(case):
    attempts = [{"date": a["date"], "outcome": OUTCOME[a["outcome"]]} for a in case["attempts"]]
    rows = review_schedule(attempts)
    expected = [
        {"kind": a["expected_kind"], "interval": a["expected_interval"], "due": a["expected_due"]}
        for a in case["attempts"]
    ]
    assert rows == expected


@cases("streak")
def test_streak(case):
    assert review_streak(case["days"], case["today"]) == case["expected_streak"]


@cases("difficulty_level")
def test_difficulty_level(case):
    attempts = [{**a, "outcome": OUTCOME[a["outcome"]]} for a in case["attempts"]]
    assert current_level(attempts, case["starting"], case["very_hard_on"]) == case["expected_level"]


@cases("sibling")
def test_sibling(case):
    chosen = choose_sibling(case["due"], case["candidates"], case.get("inactive", ()), case.get("very_hard_on", False))
    expected = case["expected_sibling"]
    assert (chosen["position"] if chosen else "original") == expected


@cases("recommendations")
def test_recommendations(case):
    state = {
        "patterns": case["patterns"],
        "advanced": case["advanced"],
        "catalog": case["catalog"],
        "scores": case.get("scores", {}),
        "unscored_attempts": case.get("unscored_attempts", {}),
        "due": [{**d, "patterns": [d["pattern"]]} for d in case.get("due", [])],
        "excluded": case.get("attempted", []) + case.get("not_now", []) + case.get("reserved", []),
        "targets": case.get("targets", []),
        "mastered": case.get("mastered", []),
        "level": case["level"],
        "advanced_on": case.get("advanced_on", False),
        "very_hard_on": case.get("very_hard_on", False),
        "focus": case.get("interview_within_14_days", False),
    }
    result = [f"{item['kind']}:{item['problem']}" for item in recommend(state)]
    assert result == case["expected_list"]


@pytest.mark.parametrize("rating, level", [
    (800, "easy"), (1199, "easy"), (1200, "medium"), (1599, "medium"),
    (1600, "hard"), (2099, "hard"), (2100, "very hard"), (3500, "very hard"), (None, None),
])
def test_codeforces_levels(rating, level):
    assert codeforces_level(rating) == level


@pytest.mark.parametrize("difficulty, level", [
    (-10000, "easy"), (399, "easy"), (400, "medium"), (1199, "medium"),
    (1200, "hard"), (1999, "hard"), (2000, "very hard"), (None, None),
])
def test_atcoder_levels(difficulty, level):
    assert atcoder_level(difficulty) == level


@pytest.mark.parametrize("interview, any_scored, expected", [
    ("2026-11-24", True, True),
    ("2026-11-25", True, False),
    ("2026-11-10", True, True),
    ("2026-11-09", True, False),
    ("2026-11-20", False, False),
    (None, True, False),
])
def test_interview_focus(interview, any_scored, expected):
    assert interview_focus(interview, "2026-11-10", any_scored) is expected
